import { z } from 'zod';

export const JournalEntrySchema = z.object({
  id: z.string(),
  title: z.string().optional().default(''),
  content: z.string().optional().default(''),
  content_html: z.string().optional(),
  type: z.enum(['memory', 'note', 'love', 'letter', 'milestone', 'gratitude', 'event']).optional().default('memory'),
  date: z.string().optional(),
  time: z.string().optional(),
  mood: z.string().optional(),
  photos: z.array(z.string()).optional().default([]),
  tags: z.array(z.string()).optional().default([]),
  author_id: z.string().optional(),
  author_name: z.string().optional(),
  author: z.string().optional(),
  location: z.any().optional(),
  location_name: z.string().optional(),
  is_favorite: z.boolean().optional().default(false),
  is_pinned: z.boolean().optional().default(false),
  metadata: z.any().optional(),
  created_at: z.string().optional(),
  updated_at: z.string().optional(),
}).transform((item) => ({
  id: item.id,
  title: item.title || '',
  content: item.content || '',
  content_html: item.content_html,
  type: item.type || 'memory',
  date: item.date || (item.created_at ? item.created_at.split('T')[0] : new Date().toISOString().split('T')[0]),
  time: item.time || (item.created_at ? new Date(item.created_at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) : '12:00'),
  mood: item.mood || 'peaceful',
  photos: Array.isArray(item.photos) ? item.photos : [],
  tags: Array.isArray(item.tags) ? item.tags : [],
  author_id: item.author_id || (item.author_name ? undefined : 'shared'),
  author_name: item.author_name || item.author || 'Kỷ niệm chung',
  location: item.location || (item.location_name ? { name: item.location_name } : undefined),
  is_favorite: Boolean(item.is_favorite),
  is_pinned: Boolean(item.is_pinned),
  metadata: item.metadata || {},
  created_at: item.created_at || new Date().toISOString(),
  updated_at: item.updated_at,
}));

export type JournalEntryEntity = z.infer<typeof JournalEntrySchema>;
